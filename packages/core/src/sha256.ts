// Synchronous SHA-256 (FIPS 180-4) over the UTF-8 encoding of a string. Core runs in the
// browser bundle as well as the server, and dedupeKey is synchronous, so neither node:crypto
// nor the async WebCrypto digest fits here. Not for secrets: this is for stable keys only.
/* eslint-disable security/detect-object-injection -- loop-bounded numeric indexes into typed arrays */

